    /// <summary>5x7 bitmap font for short labels drawn onto images. Digits, A-Z and a few symbols. Lowercase is drawn blank except d h m n o w.</summary>
    public static class PixelFont
    {
        public const int GlyphWidth = 5;
        public const int GlyphHeight = 7;

        public static int TextWidth(string text, int scale) =>
            text.Length == 0 ? 0 : text.Length * (GlyphWidth + 1) * scale - scale;

        public static void DrawText(Image<Rgba32> image, string text, int x, int y, Rgba32 color, int scale)
        {
            int advance = (GlyphWidth + 1) * scale;
            for (int i = 0; i < text.Length; i++)
            {
                if (!_glyphs.TryGetValue(text[i], out string[] rows)) continue; //unknown characters are left blank
                for (int row = 0; row < GlyphHeight; row++)
                    for (int col = 0; col < GlyphWidth; col++)
                    {
                        if (rows[row][col] != '#') continue;
                        FillRect(image, x + i * advance + col * scale, y + row * scale, scale, scale, color);
                    }
            }
        }

        /// <summary>Fills a rectangle, clipped to the image.</summary>
        public static void FillRect(Image<Rgba32> image, int x, int y, int width, int height, Rgba32 color)
        {
            for (int dy = 0; dy < height; dy++)
                for (int dx = 0; dx < width; dx++)
                {
                    int px = x + dx, py = y + dy;
                    if (px >= 0 && px < image.Width && py >= 0 && py < image.Height)
                        image[px, py] = color;
                }
        }

